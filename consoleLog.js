console.log(42);                // Positive Integer
console.log(-15.75);            // Negative number
console.log(2.56);              // Floating-point number
console.log("Hello, World!");   // String with double quotes
console.log('Hello, World!');   // String with single quotes

console.log(true);              // Boolean True
console.log(null);              // Intentional absence of value
console.log(undefined);                  // Unassigned variable state
console.log(0/0);               // Not-a-Number (e.g., 0 / 0)
console.log(1/0);               // Positive Infinity (e.g., 1 / 0)


// Comparisons
console.log(5 > 3);             // Output: true 
console.log(8 < 6);             // Output: false 
console.log(8 < -6);            // Output: false    
console.log(10 === "10");       // Output: false (Strict type comparison)
console.log(10 == "10");        // Output: true (Loose comparison)


console.log(!true);             // Output: false (Logical NOT)
console.log(2 + 2 * 5);         // Output: 12 (Math operator precedence)
console.log(typeof "42");       // Output: "string"
console.log(typeof true);       // Output: "boolean"

